-- Esquema H2 del sistema Starbucks. Seguro para ejecutarse en cada inicio.

CREATE TABLE IF NOT EXISTS perfil (
    id_perfil BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL,
    codigo VARCHAR(40) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(60) NOT NULL UNIQUE,
    clave_hash VARCHAR(255) NOT NULL,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    id_perfil BIGINT NOT NULL,
    CONSTRAINT fk_usuario_perfil FOREIGN KEY (id_perfil) REFERENCES perfil (id_perfil)
);

CREATE TABLE IF NOT EXISTS cliente (
    numero_documento VARCHAR(15) PRIMARY KEY,
    tipo_documento VARCHAR(15) NOT NULL CHECK (tipo_documento IN ('DNI', 'CE', 'RUC', 'PASAPORTE')),
    nombres VARCHAR(120) NOT NULL,
    direccion VARCHAR(250)
);

CREATE TABLE IF NOT EXISTS proveedor (
    id_proveedor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_documento VARCHAR(15) UNIQUE,
    tipo_documento VARCHAR(15) CHECK (tipo_documento IS NULL OR tipo_documento IN ('DNI', 'CE', 'RUC', 'PASAPORTE')),
    nombres VARCHAR(120) NOT NULL,
    celular VARCHAR(20),
    correo VARCHAR(120),
    direccion VARCHAR(250)
);

CREATE TABLE IF NOT EXISTS menu (
    id_menu BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS unidad_medida (
    id_unidad BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_medida VARCHAR(30) NOT NULL UNIQUE
);

-- Datos de configuración del establecimiento que emite la boleta.
CREATE TABLE IF NOT EXISTS emisor (
    id_emisor BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc VARCHAR(11) NOT NULL,
    nombre_comercial VARCHAR(120) NOT NULL,
    ubigeo VARCHAR(10),
    domicilio_fiscal VARCHAR(250),
    departamento VARCHAR(60),
    provincia VARCHAR(60),
    distrito VARCHAR(60)
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    precio_base DECIMAL(10, 2) NOT NULL CHECK (precio_base >= 0),
    descripcion VARCHAR(500),
    id_menu BIGINT NOT NULL,
    CONSTRAINT fk_producto_menu FOREIGN KEY (id_menu) REFERENCES menu (id_menu)
);

CREATE TABLE IF NOT EXISTS presentacion (
    id_presentacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL,
    nombre_opcion VARCHAR(80) NOT NULL,
    incremento_precio DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (incremento_precio >= 0),
    stock DECIMAL(12, 3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    cantidad_medida DECIMAL(12, 3),
    id_unidad BIGINT,
    CONSTRAINT fk_presentacion_producto FOREIGN KEY (id_producto) REFERENCES producto (id_producto),
    CONSTRAINT fk_presentacion_unidad FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad),
    CONSTRAINT uq_presentacion_producto_opcion UNIQUE (id_producto, nombre_opcion)
);

CREATE TABLE IF NOT EXISTS insumo (
    id_insumo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL UNIQUE,
    descripcion VARCHAR(500),
    stock_actual DECIMAL(14, 3) NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo DECIMAL(14, 3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    id_unidad BIGINT NOT NULL,
    id_proveedor BIGINT NOT NULL,
    nombre_paquete VARCHAR(100) NOT NULL,
    contenido_por_paquete DECIMAL(14, 3) NOT NULL CHECK (contenido_por_paquete > 0),
    precio_paquete DECIMAL(10, 2) NOT NULL CHECK (precio_paquete > 0),
    CONSTRAINT fk_insumo_unidad FOREIGN KEY (id_unidad) REFERENCES unidad_medida (id_unidad),
    CONSTRAINT fk_insumo_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedor (id_proveedor)
);

CREATE TABLE IF NOT EXISTS comp_carrito (
    id_comp_carrito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'CANCELADO')),
    id_usuario BIGINT NOT NULL,
    id_proveedor BIGINT NOT NULL,
    CONSTRAINT fk_comp_carrito_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_comp_carrito_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedor (id_proveedor)
);

CREATE TABLE IF NOT EXISTS comp_carrito_detalle (
    id_comp_carrito_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_comp_carrito BIGINT NOT NULL,
    id_insumo BIGINT NOT NULL,
    cantidad DECIMAL(12, 3) NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal DECIMAL(12, 2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT fk_comp_carrito_detalle_carrito FOREIGN KEY (id_comp_carrito) REFERENCES comp_carrito (id_comp_carrito),
    CONSTRAINT fk_comp_carrito_detalle_insumo FOREIGN KEY (id_insumo) REFERENCES insumo (id_insumo),
    CONSTRAINT uq_comp_carrito_insumo UNIQUE (id_comp_carrito, id_insumo)
);

CREATE TABLE IF NOT EXISTS compra (
    id_compra BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    neto DECIMAL(12, 2) NOT NULL CHECK (neto >= 0),
    igv DECIMAL(12, 2) NOT NULL CHECK (igv >= 0),
    total DECIMAL(12, 2) NOT NULL CHECK (total >= 0),
    id_usuario BIGINT NOT NULL,
    id_proveedor BIGINT NOT NULL,
    CONSTRAINT fk_compra_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_compra_proveedor FOREIGN KEY (id_proveedor) REFERENCES proveedor (id_proveedor)
);

CREATE TABLE IF NOT EXISTS compra_detalle (
    id_compra_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra BIGINT NOT NULL,
    id_insumo BIGINT NOT NULL,
    cantidad DECIMAL(12, 3) NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal DECIMAL(12, 2) NOT NULL CHECK (subtotal >= 0),
    nombre_paquete VARCHAR(100),
    nombre_insumo VARCHAR(120),
    contenido_paquete DECIMAL(14, 3),
    unidad_medida VARCHAR(30),
    CONSTRAINT fk_compra_detalle_compra FOREIGN KEY (id_compra) REFERENCES compra (id_compra),
    CONSTRAINT fk_compra_detalle_insumo FOREIGN KEY (id_insumo) REFERENCES insumo (id_insumo)
);

-- Migraciones para bases H2 existentes: conserva los datos y añade los valores históricos de cada línea.
ALTER TABLE compra_detalle ADD COLUMN IF NOT EXISTS nombre_paquete VARCHAR(100);
ALTER TABLE compra_detalle ADD COLUMN IF NOT EXISTS nombre_insumo VARCHAR(120);
ALTER TABLE compra_detalle ADD COLUMN IF NOT EXISTS contenido_paquete DECIMAL(14, 3);
ALTER TABLE compra_detalle ADD COLUMN IF NOT EXISTS unidad_medida VARCHAR(30);

CREATE TABLE IF NOT EXISTS carrito_venta (
    id_carrito_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('PENDIENTE', 'CONFIRMADO', 'CANCELADO')),
    id_usuario BIGINT NOT NULL,
    numero_documento_cliente VARCHAR(15),
    CONSTRAINT fk_carrito_venta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_carrito_venta_cliente FOREIGN KEY (numero_documento_cliente) REFERENCES cliente (numero_documento)
);

CREATE TABLE IF NOT EXISTS carrito_venta_detalle (
    id_carrito_venta_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrito_venta BIGINT NOT NULL,
    id_presentacion BIGINT NOT NULL,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_aplicado DECIMAL(10, 2) NOT NULL CHECK (precio_aplicado >= 0),
    endulzante VARCHAR(100),
    temperatura VARCHAR(100),
    tipo_molienda VARCHAR(120),
    CONSTRAINT fk_carrito_venta_detalle_carrito FOREIGN KEY (id_carrito_venta) REFERENCES carrito_venta (id_carrito_venta),
    CONSTRAINT fk_carrito_venta_detalle_presentacion FOREIGN KEY (id_presentacion) REFERENCES presentacion (id_presentacion)
);

CREATE TABLE IF NOT EXISTS venta (
    id_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    neto DECIMAL(12, 2) NOT NULL CHECK (neto >= 0),
    igv DECIMAL(12, 2) NOT NULL CHECK (igv >= 0),
    total DECIMAL(12, 2) NOT NULL CHECK (total >= 0),
    id_usuario BIGINT NOT NULL,
    numero_documento_cliente VARCHAR(15),
    CONSTRAINT fk_venta_usuario FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (numero_documento_cliente) REFERENCES cliente (numero_documento)
);

CREATE TABLE IF NOT EXISTS detalle_venta (
    id_detalle_venta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta BIGINT NOT NULL,
    id_presentacion BIGINT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_aplicado DECIMAL(10, 2) NOT NULL CHECK (precio_aplicado >= 0),
    subtotal DECIMAL(12, 2),
    producto_nombre VARCHAR(120),
    detalle VARCHAR(1000),
    endulzante VARCHAR(100),
    temperatura VARCHAR(100),
    tipo_molienda VARCHAR(120),
    CONSTRAINT fk_detalle_venta_venta FOREIGN KEY (id_venta) REFERENCES venta (id_venta),
    CONSTRAINT fk_detalle_venta_presentacion FOREIGN KEY (id_presentacion) REFERENCES presentacion (id_presentacion)
);

-- id_presentacion es opcional para ventas nuevas: la talla y las personalizaciones se guardan como detalle histórico.
