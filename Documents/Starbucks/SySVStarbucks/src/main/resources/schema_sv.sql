ALTER TABLE detalle_venta ADD COLUMN IF NOT EXISTS subtotal DECIMAL(12, 2);
ALTER TABLE detalle_venta ADD COLUMN IF NOT EXISTS producto_nombre VARCHAR(120);
ALTER TABLE detalle_venta ADD COLUMN IF NOT EXISTS detalle VARCHAR(1000);
